// The title's dirty-disc error (sub_82E64750 -> XamShowDirtyDiscErrorUI):
// raised on any failed read, and with mods, often one of theirs. Logs where
// it was raised from.
REX_EXTERN(__imp__sub_82E64750);
REX_HOOK_RAW(sub_82E64750) {
  RDAHM_ERROR("[mods] the game reports a disc read error, from {}",
              redahm::crash::GuestCallChain());
  __imp__sub_82E64750(ctx, base);
}
