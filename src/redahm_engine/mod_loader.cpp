void Install(rex::Runtime* runtime) {
  const std::vector<std::string> mods = EnabledMods();
  if (mods.empty() || !runtime || !runtime->file_system())
    return;
  auto* vfs = runtime->file_system();
  HostPathDevice* game = GameDevice(vfs);
  if (!game) {
    RDAHM_ERROR("[mods] game: isn't a host folder; mods not loaded");
    return;
  }
  const std::string mount = game->mount_path();
  const fs::path game_root = game->host_path();
  const bool read_only = game->is_read_only();
  const bool share_delete = game->allow_share_delete();
  const fs::path mods_dir = ModsDir();

  // Game path -> file, later mods over earlier ones; the mods' roots, last
  // listed first.
  std::map<std::string, ModFile> files;
  std::vector<std::pair<std::string, fs::path>> roots;
  std::vector<ModSource> sources;
  for (const std::string& mod : mods) {
    const fs::path dir = mods_dir / mod;
    std::error_code error;
    if (!fs::is_directory(dir, error)) {
      RDAHM_WARN("[mods] '{}' not found in {}", mod, mods_dir.string());
      continue;
    }
    const fs::path root = FindModRoot(dir);
    int patches = 0;
    const size_t before = files.size();
    CollectModFiles(mod, root, files, patches);
    RDAHM_INFO("[mods] '{}': {} files, {} .PackagePatch files", mod, files.size() - before, patches);
    roots.emplace(roots.begin(), mod, root);
    sources.push_back({mod, dir, root});
  }
  if (roots.empty())
    return;

  // Packages the mods edit, built (or reused) in the generated folder, which
  // sits in front of every mod.
  const fs::path generated = mods_dir / std::string(kGeneratedFolder);
  std::map<std::string, BuiltFile> built;
  std::atomic<bool> done{false};
  std::thread builder([&] {
    built = BuildPackages(sources, game_root, generated);
    done = true;
  });
  while (!done) {
#if defined(_WIN32)
    MSG message;
    PeekMessageW(&message, nullptr, 0, 0, PM_NOREMOVE);
#endif
    std::this_thread::sleep_for(std::chrono::milliseconds(50));
  }
  builder.join();
  for (const auto& [key, file] : built)
    files[key] = ModFile{file.host, file.game_path, "(built)"};
  for (const auto& [key, file] : files)
    RDAHM_DEBUG("[mods] {} <- {}", file.game_path, file.mod);
  WriteToc(game_root, files, generated / fs::path(std::string(kTocPath)));

  // The overlay gets a mount of its own and game: and d: are pointed at it.
  // The VFS hands a path to the first device, in registration order, whose
  // mount path begins it, so a device registered again at the game's mount
  // would sit behind any device mounted on a shorter prefix of it. The game's
  // own device stays where it is.
  std::vector<std::unique_ptr<Device>> layers;
  layers.push_back(std::make_unique<HostPathDevice>(kOverlayMount, generated, true));
  for (const auto& [mod, root] : roots)
    layers.push_back(std::make_unique<HostPathDevice>(kOverlayMount, root, true));
  layers.push_back(
      std::make_unique<HostPathDevice>(kOverlayMount, game_root, read_only, share_delete));
  auto overlay = std::make_unique<OverlayDevice>(kOverlayMount, std::move(layers));
  if (!overlay->Initialize()) {
    RDAHM_ERROR("[mods] couldn't read the mod folders; mods not loaded");
    return;
  }
  vfs->RegisterDevice(std::move(overlay));
  int relinked = 0;
  for (std::string_view link : {"game:", "d:", "GAME:", "D:"}) {
    std::string target;
    if (vfs->FindSymbolicLink(link, target) && Lower(target) == Lower(mount)) {
      vfs->UnregisterSymbolicLink(link);
      vfs->RegisterSymbolicLink(link, kOverlayMount);
      ++relinked;
    }
  }
  if (!relinked) {
    RDAHM_ERROR("[mods] no game: link to {} found; mods not loaded", mount);
    vfs->UnregisterDevice(kOverlayMount);
    return;
  }
  RDAHM_INFO("[mods] {} mod(s) loaded over {} ({})", roots.size(), mount, game_root.string());

  // The first file the title reads, read the way it reads it.
  File* toc = nullptr;
  rex::filesystem::FileAction action{};
  const X_STATUS status = vfs->OpenFile(
      nullptr, std::string("game:\\") + std::string(kTocPath),
      rex::filesystem::FileDisposition::kOpen, rex::filesystem::FileAccess::kGenericRead, false,
      true, &toc, &action);
  if (toc)
    toc->Destroy();
  else
    RDAHM_ERROR("[mods] the merged game folder doesn't open its TOC ({:08X})", uint32_t(status));
}

