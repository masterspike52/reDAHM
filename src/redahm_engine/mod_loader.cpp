// One entry of the merged tree. A folder holds the merged children of every
// layer's folder of that name; a file is the winning layer's file, which it
// opens (its reads, size and mapping are that file's).
class MergedEntry : public Entry {
 public:
  MergedEntry(Device* device, Entry* parent, std::string_view path, Entry* source)
      : Entry(device, parent, path), source_(source) {
    attributes_ = source->attributes();
    size_ = source->size();
    allocation_size_ = source->allocation_size();
    create_timestamp_ = source->create_timestamp();
    access_timestamp_ = source->access_timestamp();
    write_timestamp_ = source->write_timestamp();
  }

  void AddChild(std::unique_ptr<Entry> child) { children_.push_back(std::move(child)); }
  bool is_folder() const { return attributes_ & rex::filesystem::kFileAttributeDirectory; }

  X_STATUS Open(uint32_t desired_access, File** out_file) override {
    if (is_folder()) {
      // Listing walks this entry's (merged) children through the file.
      *out_file = new FolderFile(desired_access, this);
      return X_STATUS_SUCCESS;
    }
    return source_->Open(desired_access, out_file);
  }
  bool can_map() const override { return !is_folder() && source_->can_map(); }
  std::unique_ptr<rex::memory::MappedMemory> OpenMapped(rex::memory::MappedMemory::Mode mode,
                                                        size_t offset, size_t length) override {
    return is_folder() ? nullptr : source_->OpenMapped(mode, offset, length);
  }

 private:
  class FolderFile : public File {
   public:
    using File::File;
    void Destroy() override { delete this; }
    X_STATUS ReadSync(std::span<uint8_t>, size_t, size_t*) override {
      return X_STATUS_ACCESS_DENIED;
    }
    X_STATUS WriteSync(std::span<const uint8_t>, size_t, size_t*) override {
      return X_STATUS_ACCESS_DENIED;
    }
  };

  Entry* source_;
};

// The game's mount as one tree merged from the generated folder, the mods
// (last listed first) and last the game's own folder: every name comes from
// the first layer holding it, and a folder lists the children of that folder
// in every layer. Opening goes through the parent folder's children
// (VirtualFileSystem::OpenFile resolves the parent, then GetChild), so the
// merge has to be real folders rather than a per-path lookup.
class OverlayDevice : public Device {
 public:
  OverlayDevice(std::string_view mount_path, std::vector<std::unique_ptr<Device>> layers)
      : Device(mount_path), layers_(std::move(layers)) {}

  bool Initialize() override {
    std::vector<Entry*> roots;
    for (auto& layer : layers_) {
      if (!layer->Initialize())
        return false;
      if (Entry* root = layer->ResolvePath(""))
        roots.push_back(root);
    }
    if (roots.empty())
      return false;
    root_ = std::make_unique<MergedEntry>(this, nullptr, "", roots.back());
    Merge(*root_, roots);
    return true;
  }

  void Dump(rex::string::StringBuffer* string_buffer) override { base().Dump(string_buffer); }

  // The VFS hands over the path after the mount ("\KronosGame\..."), leading
  // separator and all; Entry::ResolvePath would take the empty part for a name.
  Entry* ResolvePath(const std::string_view path) override {
    Entry* entry = root_.get();
    size_t at = 0;
    while (entry && at <= path.size()) {
      const size_t end = std::min(path.find_first_of("\\/", at), path.size());
      if (end > at)
        entry = entry->GetChild(path.substr(at, end - at));
      at = end + 1;
    }
    return entry;
  }

  bool is_read_only() const override { return base().is_read_only(); }
  const std::string& name() const override { return base().name(); }
  uint32_t attributes() const override { return base().attributes(); }
  uint32_t component_name_max_length() const override {
    return base().component_name_max_length();
  }
  uint32_t total_allocation_units() const override { return base().total_allocation_units(); }
  uint32_t available_allocation_units() const override {
    return base().available_allocation_units();
  }
  uint32_t sectors_per_allocation_unit() const override {
    return base().sectors_per_allocation_unit();
  }
  uint32_t bytes_per_sector() const override { return base().bytes_per_sector(); }

 private:
  Device& base() const { return *layers_.back(); }

  static std::string Key(std::string_view name) {
    std::string key(name);
    std::transform(key.begin(), key.end(), key.begin(),
                   [](unsigned char c) { return char(std::tolower(c)); });
    return key;
  }

  static bool IsFolder(const Entry* e) {
    return e->attributes() & rex::filesystem::kFileAttributeDirectory;
  }

  // `folders`: the same folder in each layer that has it, first layer first.
  void Merge(MergedEntry& target, const std::vector<Entry*>& folders) {
    std::vector<std::string> order;
    std::map<std::string, std::vector<Entry*>> by_name;
    for (Entry* folder : folders) {
      for (const auto& child : folder->children()) {
        const std::string key = Key(child->name());
        auto& list = by_name[key];
        if (list.empty())
          order.push_back(key);
        list.push_back(child.get());
      }
    }
    for (const std::string& key : order) {
      const auto& list = by_name[key];
      Entry* top = list.front();
      const std::string path =
          target.path().empty() ? top->name() : target.path() + "\\" + top->name();
      auto child = std::make_unique<MergedEntry>(this, &target, path, top);
      if (IsFolder(top)) {
        std::vector<Entry*> sub;
        for (Entry* e : list) {
          if (IsFolder(e))
            sub.push_back(e);
        }
        Merge(*child, sub);
      }
      target.AddChild(std::move(child));
    }
  }

  std::vector<std::unique_ptr<Device>> layers_;
  std::unique_ptr<MergedEntry> root_;
};

std::string Lower(std::string_view text) {
  std::string out(text);
  std::transform(out.begin(), out.end(), out.begin(),
                 [](unsigned char c) { return char(std::tolower(c)); });
  return out;
}

std::string Trim(std::string_view text) {
  const size_t begin = text.find_first_not_of(" \t");
  if (begin == std::string_view::npos)
    return {};
  const size_t end = text.find_last_not_of(" \t");
  return std::string(text.substr(begin, end - begin + 1));
}

std::vector<std::string> EnabledMods() {
  std::vector<std::string> mods;
  std::stringstream list(REXCVAR_GET(redahm_mods));
  std::string item;
  while (std::getline(list, item, ',')) {
    if (std::string name = Trim(item); !name.empty())
      mods.push_back(std::move(name));
  }
  return mods;
}

fs::path ModsDir() {
  const std::string configured = REXCVAR_GET(redahm_mods_dir);
  if (!configured.empty()) {
    const fs::path dir(configured);
    return dir.is_absolute() ? dir : g_config_dir / dir;
  }
  return g_config_dir / "mods";
}

// A game-relative path as the game writes it (backslashes).
std::string GamePath(const fs::path& relative) {
  std::string path = relative.generic_string();
  std::replace(path.begin(), path.end(), '/', '\\');
  return path;
}

// Package edits and texture pack data: built, not served.
bool IsToolFile(const fs::path& file) {
  const std::string extension = Lower(file.extension().string());
  return extension == ".packagepatch" || extension == ".tfcmapping" || extension == ".tfc";
}

struct ModFile {
  fs::path host;
  std::string game_path;  // as found in the mod
  std::string mod;
};

// The files a mod replaces or adds, by lower-cased game path.
void CollectModFiles(const std::string& mod, const fs::path& root,
                     std::map<std::string, ModFile>& files, int& patches) {
  std::error_code error;
  for (auto it = fs::recursive_directory_iterator(root, error);
       !error && it != fs::recursive_directory_iterator(); it.increment(error)) {
    if (!it->is_regular_file())
      continue;
    const fs::path relative = fs::relative(it->path(), root, error);
    if (error || relative.parent_path().empty())
      continue;  // top-level files: readmes, tool profiles
    if (IsToolFile(relative)) {
      if (Lower(relative.extension().string()) == ".packagepatch")
        ++patches;
      continue;
    }
    const std::string game_path = GamePath(relative);
    files[Lower(game_path)] = ModFile{it->path(), game_path, mod};
  }
}

// The TOC's second column for a file: a fully compressed package's
// uncompressed size (its one compressed chunk's total), else 0.
std::string UncompressedSize(const fs::path& file) {
  std::ifstream in(file, std::ios::binary);
  unsigned char head[16] = {};
  if (!in.read(reinterpret_cast<char*>(head), sizeof(head)))
    return "0";
  auto be32 = [&](int at) {
    return uint32_t(head[at]) << 24 | uint32_t(head[at + 1]) << 16 | uint32_t(head[at + 2]) << 8 |
           head[at + 3];
  };
  const bool fully_compressed = be32(0) == 0x9E2A83C1 && be32(4) == 0x20000;
  return fully_compressed ? std::to_string(be32(12)) : "0";
}

// Where a mod's game files start: the first folder, breadth first and at most
// three levels down, holding KronosGame. The mod's own folder when there is
// none.
fs::path FindModRoot(const fs::path& dir) {
  std::vector<fs::path> level{dir};
  for (int depth = 0; depth <= 3 && !level.empty(); ++depth) {
    std::vector<fs::path> next;
    for (const fs::path& folder : level) {
      std::error_code error;
      if (fs::is_directory(folder / "KronosGame", error))
        return folder;
      for (auto it = fs::directory_iterator(folder, error);
           !error && it != fs::directory_iterator(); it.increment(error)) {
        if (it->is_directory())
          next.push_back(it->path());
      }
    }
    level = std::move(next);
  }
  return dir;
}

// The game's TOC with each replaced file's size and a line for each added one.
bool WriteToc(const fs::path& game_root, const std::map<std::string, ModFile>& files,
              const fs::path& out_path) {
  std::ifstream in(game_root / fs::path(std::string(kTocPath)), std::ios::binary);
  if (!in) {
    RDAHM_WARN("[mods] no {} in {}; file sizes left to the game", kTocPath, game_root.string());
    return false;
  }
  std::ostringstream out;
  std::map<std::string, bool> listed;
  std::string line;
  int replaced = 0;
  while (std::getline(in, line)) {
    if (!line.empty() && line.back() == '\r')
      line.pop_back();
    std::istringstream fields(line);
    std::string size, second, third, path, crc;
    if (!(fields >> size >> second >> third >> path >> crc)) {
      out << line << "\r\n";
      continue;
    }
    std::string game_path = path;
    if (game_path.rfind(kTocPrefix, 0) == 0)
      game_path.erase(0, kTocPrefix.size());
    const std::string key = Lower(game_path);
    listed[key] = true;
    if (auto it = files.find(key); it != files.end()) {
      std::error_code error;
      const auto new_size = fs::file_size(it->second.host, error);
      if (!error) {
        size = std::to_string(new_size);
        second = UncompressedSize(it->second.host);
        ++replaced;
      }
    }
    out << size << ' ' << second << ' ' << third << ' ' << path << ' ' << crc << "\r\n";
  }
  int added = 0;
  for (const auto& [key, file] : files) {
    if (listed.count(key) || key == Lower(kTocPath))
      continue;
    std::error_code error;
    const auto size = fs::file_size(file.host, error);
    if (error)
      continue;
    out << size << ' ' << UncompressedSize(file.host) << " 0 " << kTocPrefix << file.game_path
        << " 0\r\n";
    ++added;
  }
  fs::create_directories(out_path.parent_path());
  std::ofstream toc(out_path, std::ios::binary | std::ios::trunc);
  toc << out.str();
  RDAHM_INFO("[mods] TOC: {} sizes updated, {} files added", replaced, added);
  return bool(toc);
}

// game:'s device: the runtime mounts the game data folder as a host path
// device and links game: and d: to it.
HostPathDevice* GameDevice(rex::filesystem::VirtualFileSystem* vfs) {
  for (std::string_view link : {"game:", "game:\\", "d:", "d:\\"}) {
    if (Entry* entry = vfs->ResolvePath(link)) {
      if (auto* device = dynamic_cast<HostPathDevice*>(entry->device()))
        return device;
    }
  }
  return nullptr;
}

