// Drop-in mods.
//
// A mod is a folder under mods/ (beside redahm.exe, or redahm_mods_dir). It
// holds files laid out like the game's data folder, either directly
// (mods/MyMod/KronosGame/CookedXenon/UI_FrontEnd_Loading.xxx) or under Game/
// as the TFC Installer lays mods out (mods/MyMod/Game/KronosGame/...). Files
// at a mod's top level (readmes, UPK Explorer profiles) are ignored.
//
// redahm_mods lists the mods to use, comma separated; when two of them carry
// the same file the later one wins. The game's own files fill in the rest.
//
// The runtime mounts the game data folder as one host path device, reached
// through game: and d:. Install builds one tree from the generated folder, each
// enabled mod (last listed first) and the game folder: every name comes from
// the first of them that has it, and every folder lists the files of all of
// them (the VFS opens a file by finding its folder and then the name inside
// it, and UE3 finds its packages by listing CookedXenon). A file opens as the
// real file it stands for. The tree gets a mount of its own and game: and d:
// are pointed at it; the game's own device stays mounted as it was.
//
// UE3 on the 360 takes file sizes from KronosGame\Xbox360TOC.txt ("size
// uncompressed-size 0 ..\path crc" per line) rather than from the file
// system, so a replacement whose size differs, or a file the game doesn't
// have, needs its line. The second column is non-zero for a fully compressed
// package (Engine.xxx, KronosGame.xxx...), which the game unpacks whole as it
// opens it; a replacement's comes from its own contents (0 for the
// uncompressed packages built here). The merged TOC is written to
// mods/_generated, which sits in front of every mod.
//
// A mod's game files start at the first folder, at most three levels down,
// holding KronosGame, so a mod kept in wrapper folders
// (mods/Re-Enlightened/MyMod/Game/KronosGame/...) works as it is.
//
// The first build of a mod set can take the better part of a minute. It runs
// on worker threads while this thread (the window's) keeps looking at its
// message queue, so Windows doesn't take the window for hung.
//
// Package edits (.PackagePatch files and texture packs, as the TFC Installer
// applies them) are built into mods/_generated by mod_build.cpp and served
// from there.

